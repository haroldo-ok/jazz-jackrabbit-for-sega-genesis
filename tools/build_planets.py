#!/usr/bin/env python3
"""Convert the shareware PLANET.### approach screens to sparse tile frames.

Original layout, palette, 64x55 planet pixels and FONTMN1 glyphs follow
OpenJazz's JJ1Planet.  At runtime frames approximate the original scaling
curve while remaining within Genesis VRAM and unbanked ROM limits.
"""
import argparse
from pathlib import Path
from PIL import Image
from import_jj1_shareware import Reader
from build_sgdk_scenes import palettize, color_line

SOURCES = ('000', '001', '002', '018')
# 100-ms approach samples over 2 sec, followed by a 2-sec pause at 2x,
# then four 62.5-ms samples of the original quarter-second rapid zoom.
SCALES = [i / 10 for i in range(1, 21)] + [4, 6, 8, 10]


def font(path):
    r = Reader(path.read_bytes())
    if r.block(19) != b'Digital Dimensions\x1a': raise ValueError('invalid font')
    space, height = r.byte(), r.byte(); glyphs = []
    while r.pos < len(r.data):
        size = r.u16()
        if size > 4:
            raw = r.rle(size); w = raw[0] | raw[1] << 8; h = raw[2] | raw[3] << 8
            if 4+w*h > len(raw): raise ValueError('invalid glyph')
            glyphs.append((w, h, raw[4:4+w*h]))
        else: glyphs.append((0, 0, b''))
    return space, height, glyphs


def planet(path):
    r=Reader(path.read_bytes()); ident=r.u16(); length=r.byte()
    name=r.block(length).decode('ascii').lower()
    raw=r.block(768); colors=[tuple((v<<2)|(v>>4) for v in raw[i:i+3]) for i in range(0,768,3)]
    pixels=r.block(64*55)
    if r.pos != len(r.data): raise ValueError('unexpected trailing planet data')
    return ident, name, colors, pixels


def text(image, string, top, face):
    space, height, glyphs = face
    codes = [(ord(c)-96 if 'a'<=c<='z' else None) for c in string]
    widths = [(glyphs[c][0]+2 if c is not None and c < len(glyphs) else space) for c in codes]
    x = (320-sum(widths)) // 2
    for c, width in zip(codes,widths):
        if c is not None and c < len(glyphs):
            w,h,pix = glyphs[c]
            for y in range(h):
                for dx in range(w):
                    value=pix[y*w+dx]
                    if value and 0<=x+dx<320 and 0<=top+y<200: image.putpixel((x+dx, top+y),value)
        x += width


def render(name, pixels, face, scale):
    image=Image.new('L',(320,200),0)
    source=Image.frombytes('L',(64,55),pixels)
    w=max(1,int(64*scale)); h=max(1,int(55*scale))
    sprite=source.resize((w,h),Image.Resampling.NEAREST)
    mask=sprite.point(lambda x: 255 if x else 0)
    image.paste(sprite,((320-w)//2,(200-h)//2),mask)
    text(image,'now approaching',2,face)
    text(image,name,198-face[1],face)
    return image.tobytes()


def convert(root,out,inc):
    out.mkdir(parents=True,exist_ok=True); face=font(root/'FONTMN1.0FN')
    lines=['/* Generated by tools/build_planets.py; do not edit. */']
    for ext in SOURCES:
        ident,name,palette,pixels=planet(root/('PLANET.'+ext))
        frames=[render(name,pixels,face,scale) for scale in SCALES]
        cols,tiles=palettize(frames,palette)
        data=bytearray(tiles[0]); transitions=[]
        for a,b in zip(tiles,tiles[1:]):
            changed=[i for i in range(1000) if a[i*32:i*32+32]!=b[i*32:i*32+32]]
            runs=[]
            for i in changed:
                if runs and i==runs[-1][0]+runs[-1][1]:runs[-1]=(runs[-1][0],runs[-1][1]+1)
                else:runs.append((i,1))
            offset=len(data)
            for start,count in runs:data.extend(b[start*32:(start+count)*32])
            transitions.append((runs,offset))
        (out/f'planet_{ext}.bin').write_bytes(data)
        lines.append(color_line('planet_'+ext,cols))
        for i,(runs,_) in enumerate(transitions):
            if not runs: raise ValueError('empty planet transition')
            lines.append(f'static const SceneRun planet_{ext}_runs_{i}[] = {{ '+', '.join('{%d,%d}'%v for v in runs)+' };')
        lines.append(f'static const SparseDelta planet_{ext}_deltas[] = {{')
        for i,(runs,offset) in enumerate(transitions):
            lines.append(f'    {{planet_{ext}_runs_{i}, {len(runs)}, {offset}UL, 0}},')
        lines.append('};')
        lines.append(f'static const PlanetScene planet_{ext} = {{ {ident}, jj1_scene_planet_{ext}, planet_{ext}_pal, planet_{ext}_deltas }};')
        print(ext,name,'id',ident,'frames',len(tiles),'bytes',len(data))
    lines.append('static const PlanetScene *const planet_scenes[] = { '+', '.join('&planet_'+e for e in SOURCES)+' };')
    inc.write_text('\n'.join(lines)+'\n')

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--input',type=Path,required=True)
    p.add_argument('--out-res',type=Path,default=Path('res/scenes'))
    p.add_argument('--out-inc',type=Path,default=Path('src/jj1_planet_data.inc'))
    a=p.parse_args();convert(a.input,a.out_res,a.out_inc)
